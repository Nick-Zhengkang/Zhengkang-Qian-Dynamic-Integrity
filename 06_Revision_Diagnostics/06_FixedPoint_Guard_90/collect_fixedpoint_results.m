function T=collect_fixedpoint_results(out)
% AI-assisted collection from MAT structs, never auto-detected CSV headers.
files=dir(fullfile(out,'*_seed_*','case_result.mat')); rows=cell(numel(files),1);
for k=1:numel(files)
    F=load(fullfile(files(k).folder,files(k).name),'summary'); rows{k}=F.summary;
end
assert(~isempty(rows),'No completed case records to collect.');
T=struct2table(vertcat(rows{:})); T=sortrows(T,{'model','seed'});
writetable(T,fullfile(out,'per_case_summary.csv'));
ids=["quadratic_cubic","bistable_duffing","genda_cosine_quadratic_drag"];
groups=cell(3,1);
for k=1:3
    A=T(T.model==ids(k),:); done=A.status=="complete";
    validated=done & A.winning_validation=="both_solvers_support_non_target";
    contradicted=done & A.winning_validation=="both_solvers_support_target";
    groups{k}=struct('model',ids(k),'expected_cases',30,'recorded_cases',height(A), ...
        'complete_cases',nnz(done),'error_cases',nnz(A.status=="error"), ...
        'control_reproduced',nnz(A.control_reproduced), ...
        'finite_estimates',nnz(done & isfinite(A.R_hat)), ...
        'under_reference',nnz(done & A.under_reference), ...
        'winning_non_target_supported',nnz(validated), ...
        'winning_label_contradicted',nnz(contradicted), ...
        'winning_unresolved_or_missing',nnz(done & ~validated & ~contradicted), ...
        'all_checked_non_target_supported',nnz(done & A.all_checked_non_target_supported), ...
        'time_guard_hits',nnz(A.time_guard_hit), ...
        'runs_with_fixed_rejection',nnz(done & A.fixed_rejected>0), ...
        'fixed_point_rejections',sum(A.fixed_rejected(done),'omitnan'), ...
        'fixed_point_acceptances',sum(A.fixed_accepted(done),'omitnan'), ...
        'periodic_terminations',sum(A.periodic_terminations(done),'omitnan'), ...
        'forced_non_target',sum(A.forced_non_target_count(done),'omitnan'), ...
        'median_absolute_error_percent',median(A.absolute_error_percent(done),'omitnan'));
end
S=struct2table(vertcat(groups{:}));
writetable(S,fullfile(out,'summary_by_model.csv'));
save(fullfile(out,'summary.mat'),'T','S');
fprintf('Recorded %d/90 cases; complete %d; errors %d.\n',height(T), ...
    nnz(T.status=="complete"),nnz(T.status=="error"));
disp(S(:,{'model','complete_cases','under_reference','winning_non_target_supported', ...
    'winning_label_contradicted','winning_unresolved_or_missing'}));
end
