function trigger=audit_query567_samples(xt,cells,g,d,out)
% AI-assisted offline observation. Every row is checked against the untouched
% step function using the exact states and history from the native integrator.
n=size(xt,1); rows=cell(n-1,1);
assert(numel(cells)==n && n>=2);
for sample=2:n
    z=xt(sample,:); previous=cells(1:sample-1);
    [kind,cid]=sampled_forward_step(z,g,d,previous);
    assert(cid==cells(sample),'Grid lookup mismatch at sample %d.',sample);
    s=recurrence_statistics(previous,cid,d);
    inside=all(z>d.domain(1:2) & z<d.domain(3:4));
    targetHit=ismember(cid,g.cell_c);
    recurrenceReached=inside && ~targetHit && s.history_gate;
    branch="none"; expectedKind=0;
    if ~inside
        expectedKind=3; branch="direct_domain_exit";
    elseif targetHit
        expectedKind=1; branch="target_cache";
    elseif recurrenceReached && s.counter_branch~="none"
        expectedKind=4; branch=s.counter_branch;
    end
    assert(kind==expectedKind,'Observer disagrees with native step at sample %d.',sample);
    if sample<n, assert(kind==0,'Trajectory continued beyond a native classification.'); end
    dz=sistema((sample-1)*d.Ts,z(:),d.par);
    rows{sample-1}=struct('sample_index',sample,'time',(sample-1)*d.Ts, ...
        'x',z(1),'v',z(2),'rhs_norm',norm(dz),'cell_id',cid, ...
        'native_kind',kind,'executed_branch',branch,'inside_domain',inside, ...
        'target_cache_hit',targetHit,'negative_cache_member_ignored',ismember(cid,g.cell_d), ...
        'exit_cache_member_ignored',ismember(cid,g.cell_dout), ...
        'recurrence_reached',recurrenceReached, ...
        'previous_visit_count',s.previous_visit_count, ...
        'adjacent_gap_count',s.adjacent_gap_count,'nonadjacent_gap_count',s.nonadjacent_gap_count, ...
        'rep_fix_point',double(d.repFixPoint),'rep_periodic',double(d.repPeriodic), ...
        'fixed_condition',s.fixed_condition,'periodic_count_gate',s.periodic_count_gate, ...
        'periodic_not_immediate_gate',s.periodic_not_immediate_gate, ...
        'periodic_gap_condition',s.periodic_gap_condition, ...
        'periodic_condition_if_checked',s.periodic_condition, ...
        'periodic_outer_condition_evaluated',recurrenceReached && ~s.fixed_condition, ...
        'periodic_inner_condition_evaluated',recurrenceReached && ~s.fixed_condition && s.periodic_gate, ...
        'first_previous_sample',s.first_previous_sample, ...
        'last_previous_sample',s.last_previous_sample, ...
        'current_streak_including_current',s.current_streak_including_current);
end
T=struct2table(vertcat(rows{:})); writetable(T,fullfile(out,'sample_audit.csv'));
trigger=T(end,:);
assert(trigger.native_kind==4 && any(trigger.executed_branch==["rep_fix_point","rep_periodic"]), ...
    'The reproduced terminal event was not a recurrence classification.');
cid=trigger.cell_id;
ix=floor((cid-1)/d.discr)+1; iv=mod(cid-1,d.discr)+1;
trigger.cell_x_min=g.cell_pos(ix,1)-g.dh(1)/2;
trigger.cell_x_max=g.cell_pos(ix,1)+g.dh(1)/2;
trigger.cell_v_min=g.cell_pos(iv,2)-g.dh(2)/2;
trigger.cell_v_max=g.cell_pos(iv,2)+g.dh(2)/2;
writetable(trigger,fullfile(out,'trigger_summary.csv'));

visits=find(cells==cid); visitedTimes=(visits-1)*d.Ts;
gap=[NaN;diff(visits)]; usedInCondition=visits<n;
V=table(visits,visitedTimes,gap,gap*d.Ts,usedInCondition, ...
    'VariableNames',{'sample_index','time','gap_samples','gap_time','used_in_trigger_history'});
writetable(V,fullfile(out,'trigger_cell_visits.csv'));
prior=visits(visits<n);
G=table(prior(1:end-1),prior(2:end),diff(prior),diff(prior)==1,diff(prior)~=1, ...
    'VariableNames',{'from_sample','to_sample','gap_samples','counts_for_fixed','counts_for_periodic'});
writetable(G,fullfile(out,'trigger_history_gaps.csv'));
starts=[1;find(diff(visits)>1)+1]; ends=[starts(2:end)-1;numel(visits)];
episodes=table((1:numel(starts)).',visits(starts),visits(ends), ...
    visitedTimes(starts),visitedTimes(ends),ends-starts+1, ...
    'VariableNames',{'episode','first_sample','last_sample','first_time','last_time','sample_count'});
writetable(episodes,fullfile(out,'trigger_cell_episodes.csv'));
writetable(T(T.cell_id==cid,:),fullfile(out,'trigger_cell_counter_history.csv'));
end
