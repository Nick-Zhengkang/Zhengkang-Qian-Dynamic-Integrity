function out=ma_design(action,varargin)
names={'qk','discr','generations','population','newcomers','selected','number_of_steps','Ts'};
switch action
    case 'names'
        out=names;
    case 'matrix'
        out=varargin{1}{:,names};
    case 'baseline'
        out=[1 701 5 20 8 3 100 .05];
    case 'feasible'
        x=varargin{1}; o=varargin{2};
        if istable(x), x=x{:,names}; end
        out=all(isfinite(x) & x>=o.lower & x<=o.upper,2) ...
            & all(x(:,1:7)==round(x(:,1:7)),2) ...
            & x(:,5)>=.2*x(:,4)-1e-10 & x(:,5)<=.6*x(:,4)+1e-10 ...
            & x(:,4)-1-x(:,5)-2>=1 & x(:,6)<=x(:,4);
    case 'key'
        x=varargin{1};
        out=ma_io('hash',uint8([sprintf('%d_',x(1:7)) num2hex(x(8))]));
        out=out(1:24); % Cached records also verify the exact configuration.
    case 'config'
        x=varargin{1}; model=varargin{2};
        assert(any(strcmp(model,{'quadratic_cubic','bistable_duffing'})));
        domain=[-3 -2 3 4];
        out=struct('tfinal',2000,'Ts',x(8),'weight',[1 1],'type_x0',1, ...
            'reltol',1e-8,'abstol',1e-8,'number_of_steps',x(7), ...
            'num_of_cell_around_equilibrium',2*x(1)+1,'num_fig',1001, ...
            'plot_results',0,'plot_results_final',0,'spaceboundary',domain, ...
            'discr',x(2),'automatic',1,'var1',1,'var2',2, ...
            'rep_fix_point',40,'rep_periodic',10,'min_periodic_radius',.005, ...
            'check_min_periodic',0,'check_equilibrium',1,'max_check_step',10000, ...
            'divR',40,'num_gen',x(3),'num_crossover',x(4)-1-x(5)-2, ...
            'selected_opt',x(6),'newcomers',x(5),'num_almost_clones',2,'bis_iter_max',5);
    case 'order'
        out={'tfinal','Ts','weight','type_x0','reltol','abstol', ...
            'number_of_steps','num_of_cell_around_equilibrium','num_fig', ...
            'plot_results','plot_results_final','spaceboundary','discr', ...
            'automatic','var1','var2','rep_fix_point','rep_periodic', ...
            'min_periodic_radius','check_min_periodic','check_equilibrium', ...
            'max_check_step','divR','num_gen','num_crossover','selected_opt', ...
            'newcomers','num_almost_clones','bis_iter_max'};
    otherwise
        error('Unknown design action.');
end
end
