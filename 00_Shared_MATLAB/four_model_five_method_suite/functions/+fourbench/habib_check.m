function habib_check(T,folder)
if ~all(T.benchmark=="paper_unforced_duffing"), return; end
z=T(T.method=="dynin_original_bisection",:); valid=z.success & isfinite(z.R_num);
pass=valid & z.relative_absolute_error<=.01;
report=table(.7683,sum(valid),height(z),mean(z.R_num(valid)), ...
    median(z.relative_absolute_error(valid)),mean(pass), ...
    'VariableNames',{'published_LIM','valid_runs','attempted_runs','mean_LIM', ...
    'median_relative_absolute_error','fraction_within_1pct'});
writetable(report,fullfile(folder,'habib_reproduction_check.csv'));
disp(report);
if ~all(valid) || mean(pass)<.9
    warning('fourbench:HabibCheck', ...
        ['Habib reproduction check needs review: fewer than 90%% of all attempts ', ...
         'are valid and within 1%%. This is a reporting threshold, not an algorithm stop. ', ...
         'Do not claim successful reproduction before reviewing raw data.']);
end
end
