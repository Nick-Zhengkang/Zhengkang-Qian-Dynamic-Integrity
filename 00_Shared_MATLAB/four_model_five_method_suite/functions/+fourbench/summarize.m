function S=summarize(T,byAlpha)
methods=unique(T.method,'stable');
if byAlpha, alphas=unique(T.alpha,'stable'); else, alphas=NaN; end
rows={};
for a=alphas(:)'
    for m=methods(:)'
        all=T.method==m;
        if byAlpha, all=all & T.alpha==a; end
        ok=all & T.success & isfinite(T.R_num);
        er=T.signed_error(ok); ae=T.absolute_error(ok);
        rows(end+1,:)={a,m,sum(all),sum(ok),mean(~T.success(all)), ...
            mean(T.R_ref(all),'omitnan'),mean(T.R_num(ok),'omitnan'), ...
            mean(er,'omitnan'),mean(ae,'omitnan'),median(ae,'omitnan'), ...
            sqrt(mean(er.^2,'omitnan')),mean(T.relative_absolute_error(ok),'omitnan'), ...
            mean(T.unsafe_overestimation(ok),'omitnan'), ...
            mean(T.within_1pct(all)),mean(T.within_2pct(all)),mean(T.within_5pct(all)), ...
            mean(T.runtime_s(all),'omitnan'),median(T.runtime_s(all),'omitnan'), ...
            std(T.runtime_s(all),'omitnan'),mean(T.trajectory_evaluations(all),'omitnan')}; %#ok<AGROW>
    end
end
S=cell2table(rows,'VariableNames',{'alpha','method','n_runs','n_success','failure_rate', ...
    'R_ref_mean','R_num_mean','mean_signed_error','mean_absolute_error', ...
    'median_absolute_error','RMSE','mean_relative_absolute_error', ...
    'unsafe_overestimation_rate','within_1pct_rate','within_2pct_rate','within_5pct_rate', ...
    'mean_runtime_s','median_runtime_s','std_runtime_s','mean_trajectory_evaluations'});
% Runtime includes failures. Accuracy-pass denominators include all attempts.
end
